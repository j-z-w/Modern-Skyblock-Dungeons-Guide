package kr.syeyoung.dungeonsguide.mod.utils;

// net.minecraft.util.Tuple was removed in 26.3; this keeps the same semantics
// (mutable pair, no equals/hashCode -> identity semantics)
public class Tuple<A, B> {
    private A a;
    private B b;

    public Tuple(A a, B b) {
        this.a = a;
        this.b = b;
    }

    public A getA() {
        return a;
    }

    public void setA(A a) {
        this.a = a;
    }

    public B getB() {
        return b;
    }

    public void setB(B b) {
        this.b = b;
    }
}
